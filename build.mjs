/* Build a single self-contained HTML file from src/ + vendor/katex. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const dist = path.join(root, 'vendor', 'katex');

const read = (p) => fs.readFileSync(p, 'utf8');
const b64 = (p) => fs.readFileSync(p).toString('base64');

// ---------- KaTeX CSS with inlined woff2 fonts ----------
let katexCss = read(path.join(dist, 'katex.min.css'));
let fontCount = 0;
katexCss = katexCss.replace(
  /url\(fonts\/([^)]+\.woff2)\)\s*format\("woff2"\),\s*url\([^)]+\)\s*format\("woff"\),\s*url\([^)]+\)\s*format\("truetype"\)/g,
  (m, file) => {
    const p = path.join(dist, 'fonts', file);
    if (!fs.existsSync(p)) throw new Error('missing font ' + file);
    fontCount++;
    return 'url(data:font/woff2;base64,' + b64(p) + ') format("woff2")';
  }
);
if (fontCount !== 20) throw new Error('expected 20 KaTeX fonts, inlined ' + fontCount);

// ---------- KaTeX JS ----------
let katexJs = read(path.join(dist, 'katex.min.js'));
katexJs = katexJs.replace(/<\/script/gi, '<\\/script');

// ---------- app sources ----------
const appCss = read(path.join(root, 'src', 'app.css'));
const paletteJs = read(path.join(root, 'src', 'palette.js'));
const appJs = read(path.join(root, 'src', 'app.js')).replace(/<\/script/gi, '<\\/script');
let html = read(path.join(root, 'src', 'index.html'));

html = html.replace('<!doctype html>', () => '<!doctype html>\n<!-- Generated by build.mjs. Edit src/ and run: node build.mjs -->');
html = html.replace('<!--KATEX_CSS-->', () => '<style>\n' + katexCss + '\n</style>');
html = html.replace('<!--APP_CSS-->', () => '<style>\n' + appCss + '\n</style>');
html = html.replace('<!--PALETTE_JS-->', () => '<script>\n' + paletteJs + '\n</script>');
html = html.replace('<!--KATEX_JS-->', () => '<script>\n' + katexJs + '\n</script>');
html = html.replace('<!--APP_JS-->', () => '<script>\n' + appJs + '\n</script>');

if (/<!--(KATEX_CSS|APP_CSS|PALETTE_JS|KATEX_JS|APP_JS)-->/.test(html)) {
  throw new Error('placeholder left un-replaced');
}

const outFile = path.join(root, 'index.html');
fs.writeFileSync(outFile, html, 'utf8');
const kb = (fs.statSync(outFile).size / 1024).toFixed(0);
console.log('built', outFile);
console.log('size:', kb + ' KB | fonts inlined:', fontCount);
